def main():
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    all_locales = {}

    for code in LANGUAGES.keys():
        json_file = os.path.join(LOCALES_DIR, f"{code}.json")
        data = {}
        if os.path.exists(json_file):
            with open(json_file, "r", encoding="utf-8") as f:
                data = json.load(f)
        
        # Merge extra keys
        extras = EXTRAS.get(code, EXTRAS["en"])
        data["extras"] = extras
        data["langMeta"] = LANGUAGES[code]
        all_locales[code] = data

    js_content = "/* Autogenerated locales bundle for DhenuRakshak AI (SIH 109) */\n"
    js_content += "window.LOCALES = " + json.dumps(all_locales, ensure_ascii=False, indent=2) + ";\n"
    js_content += "window.AVAILABLE_LANGUAGES = " + json.dumps(LANGUAGES, ensure_ascii=False, indent=2) + ";\n"

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"✅ Generated {OUTPUT_PATH} with {len(all_locales)} languages successfully!")


if __name__ == "__main__":
    main()
